// baseRune folds case and splits Spanish accented letters into a base glyph
// plus a mark drawn above it.
func baseRune(r rune) (rune, accent) {
	switch r {
	case 'Á', 'á':
		return 'A', acute
	case 'É', 'é':
		return 'E', acute
	case 'Í', 'í':
		return 'I', acute
	case 'Ó', 'ó':
		return 'O', acute
	case 'Ú', 'ú':
		return 'U', acute
	case 'Ñ', 'ñ':
		return 'N', tilde
	case 'Ü', 'ü':
		return 'U', diaeresis
	}
	if r >= 'a' && r <= 'z' {
		r -= 'a' - 'A'
	}
	return r, noAccent
}
