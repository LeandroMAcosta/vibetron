type accent uint8

const (
	noAccent accent = iota
	acute
	tilde
	diaeresis
)

type pt struct{ x, y int8 }

// accentDots are offsets from the glyph's top-left; a blank row separates
// each mark from the letter so a full top bar (É) stays readable.
